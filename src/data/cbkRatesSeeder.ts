// Helper to retrieve CBK Rates Seeder with localStorage persistent updates
export function getSeededCbkRates(): CbkRateItem[] {
  try {
    const saved = localStorage.getItem('sunnyremit_cbk_rates_seeder');
    if (saved) {
      return JSON.parse(saved);
    }
  } catch (e) {
    console.warn('Could not read saved CBK rates seeder:', e);
  }
  return CBK_RATES_SEEDER;
}

export function saveCbkRatesSeeder(rates: CbkRateItem[]): void {
  try {
    localStorage.setItem('sunnyremit_cbk_rates_seeder', JSON.stringify(rates));
  } catch (e) {
    console.warn('Could not save CBK rates seeder:', e);
  }
}

export function resetCbkRatesSeeder(): CbkRateItem[] {
  try {
    localStorage.removeItem('sunnyremit_cbk_rates_seeder');
  } catch (e) {
    // ignore
  }
  return CBK_RATES_SEEDER;
}
